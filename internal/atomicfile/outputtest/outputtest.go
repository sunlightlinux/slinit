// Package outputtest checks that a converter's --output-dir writes go
// through atomicfile: a rerun regenerates an existing service file in
// place, as it always did, and a symlink planted at an output name is
// refused rather than written through.
package outputtest

import (
	"os"
	"path/filepath"
	"testing"
)

// Check runs a converter's main (through run, which returns its exit
// error) on inputs with --output-dir, and checks what it does to what
// is already in that directory.
func Check(t *testing.T, run func(args ...string) error, inputs ...string) {
	t.Helper()
	// Created up front: slinit-sysvinit-convert wants it to exist.
	out := filepath.Join(t.TempDir(), "out")
	if err := os.Mkdir(out, 0o755); err != nil {
		t.Fatal(err)
	}
	args := append([]string{"--output-dir", out}, inputs...)
	if err := run(args...); err != nil {
		t.Fatalf("first conversion into an empty directory: %v", err)
	}
	ents, err := os.ReadDir(out)
	if err != nil || len(ents) == 0 {
		t.Fatalf("no output written to %s: %v", out, err)
	}
	var names []string
	for _, e := range ents {
		names = append(names, e.Name())
	}

	// A rerun regenerates an existing file: operators re-run the
	// converters, and replacing was always the behaviour.
	for _, n := range names {
		if err := os.WriteFile(filepath.Join(out, n), []byte("stale\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if err := run(args...); err != nil {
		t.Errorf("rerun over existing files: %v", err)
	}
	for _, n := range names {
		p := filepath.Join(out, n)
		if b, _ := os.ReadFile(p); string(b) == "stale\n" {
			t.Errorf("%s not regenerated by the rerun", n)
		}
		if fi, err := os.Lstat(p); err != nil || !fi.Mode().IsRegular() {
			t.Errorf("%s is not a regular file after the rerun: %v", n, err)
		}
	}
	if m, _ := filepath.Glob(filepath.Join(out, ".*.tmp-*")); len(m) != 0 {
		t.Errorf("temp files left behind: %v", m)
	}

	// A symlink at an output name is refused, never written through.
	base := t.TempDir()
	victim := filepath.Join(base, "victim")
	if err := os.WriteFile(victim, []byte("precious\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	out = filepath.Join(base, "out")
	if err := os.Mkdir(out, 0o755); err != nil {
		t.Fatal(err)
	}
	for _, n := range names {
		if err := os.Symlink("../victim", filepath.Join(out, n)); err != nil {
			t.Fatal(err)
		}
	}
	if err := run(append([]string{"--output-dir", out}, inputs...)...); err == nil {
		t.Errorf("conversion over planted symlinks exited 0")
	}
	if b, _ := os.ReadFile(victim); string(b) != "precious\n" {
		t.Errorf("symlink target rewritten: %q", b)
	}
	for _, n := range names {
		if fi, err := os.Lstat(filepath.Join(out, n)); err != nil || fi.Mode()&os.ModeSymlink == 0 {
			t.Errorf("symlink %s replaced", n)
		}
	}
}
