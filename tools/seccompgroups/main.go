// tools/seccompgroups — regenerates slinit's seccomp syscall table and
// groups from their upstream sources, so neither is hand-kept.
//
//	go run ./tools/seccompgroups -systemd ../systemd
//
// It writes two files in pkg/seccomp:
//
//   - zsyscalls_linux_amd64.go: every x86_64 syscall that
//     golang.org/x/sys/unix names (its zsysnum_linux_amd64.go, taken
//     from the kernel's syscall table), as name → unix.SYS_*.
//   - zgroups.go: systemd's SystemCallFilter= groups, read from
//     src/shared/seccomp-util.c, with nested @groups expanded and each
//     list cut to the syscalls x86_64 has. @known is every syscall in
//     the table, which is what systemd builds it from.
//
// Both used to be hand-written. The table lacked 93 syscalls (flock,
// the xattr family, io_uring_*), so a filter naming one was refused, and
// the groups had drifted from systemd's — @system-service allowed 207
// syscalls where systemd allows 313 — so a unit ported from systemd
// could be killed by a call systemd lets through.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var (
	setRe   = regexp.MustCompile(`(?s)\[SYSCALL_FILTER_SET_[A-Z_]+\] = \{\s*(?:/\*.*?\*/\s*)?\.name = "(@[a-z-]+)",\s*\.help = "([^"]*)",\s*\.value =(.*?)\n        \},`)
	entryRe = regexp.MustCompile(`"([^"]+)\\0"`)
	sysRe   = regexp.MustCompile(`SYS_([A-Z0-9_]+)\s*=\s*\d+`)
)

func main() {
	sdDir := flag.String("systemd", "../systemd", "systemd source tree")
	out := flag.String("out", "pkg/seccomp", "output directory")
	flag.Parse()
	if err := run(*sdDir, *out); err != nil {
		fmt.Fprintln(os.Stderr, "seccompgroups:", err)
		os.Exit(1)
	}
}

func run(sdDir, out string) error {
	files, summary, err := generate(sdDir)
	if err != nil {
		return err
	}
	for file, src := range files {
		if err := os.WriteFile(filepath.Join(out, file), src, 0o644); err != nil {
			return err
		}
	}
	fmt.Println("seccompgroups:", summary)
	return nil
}

// generate returns the formatted contents of the generated files.
func generate(sdDir string) (map[string][]byte, string, error) {
	xsys, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "golang.org/x/sys").Output()
	if err != nil {
		return nil, "", fmt.Errorf("locate golang.org/x/sys: %w", err)
	}
	sysSrc, err := os.ReadFile(filepath.Join(strings.TrimSpace(string(xsys)), "unix", "zsysnum_linux_amd64.go"))
	if err != nil {
		return nil, "", err
	}
	consts := map[string]string{} // name -> SYS_ constant
	for _, m := range sysRe.FindAllSubmatch(sysSrc, -1) {
		c := string(m[1])
		consts[strings.ToLower(c)] = "SYS_" + c
	}

	sdSrc, err := os.ReadFile(filepath.Join(sdDir, "src", "shared", "seccomp-util.c"))
	if err != nil {
		return nil, "", err
	}
	commit, _ := exec.Command("git", "-C", sdDir, "rev-parse", "--short=10", "HEAD").Output()

	type set struct {
		help    string
		entries []string
	}
	sets := map[string]set{}
	var order []string
	for _, m := range setRe.FindAllSubmatch(sdSrc, -1) {
		name := string(m[1])
		var entries []string
		for _, e := range entryRe.FindAllSubmatch(m[3], -1) {
			entries = append(entries, string(e[1]))
		}
		sets[name] = set{help: string(m[2]), entries: entries}
		order = append(order, name)
	}
	// Every group must be read: one the pattern skips would vanish from
	// slinit without a word, which is how @obsolete was first lost.
	if want := bytes.Count(sdSrc, []byte(`.name = "@`)); len(sets) != want {
		return nil, "", fmt.Errorf("read %d of the %d groups in seccomp-util.c; has its layout changed?", len(sets), want)
	}

	var expand func(name string, seen map[string]bool) (map[string]bool, error)
	expand = func(name string, seen map[string]bool) (map[string]bool, error) {
		s, ok := sets[name]
		if !ok {
			return nil, fmt.Errorf("group %s refers to unknown %s", name, name)
		}
		got := map[string]bool{}
		if name == "@known" {
			for n := range consts {
				got[n] = true
			}
		}
		for _, e := range s.entries {
			if strings.HasPrefix(e, "@") {
				if seen[e] {
					continue
				}
				seen[e] = true
				sub, err := expand(e, seen)
				if err != nil {
					return nil, err
				}
				for n := range sub {
					got[n] = true
				}
			} else if _, ok := consts[e]; ok {
				got[e] = true
			}
		}
		return got, nil
	}

	var g bytes.Buffer
	fmt.Fprintf(&g, "// Code generated by tools/seccompgroups from systemd %s; DO NOT EDIT.\n\n", strings.TrimSpace(string(commit)))
	g.WriteString("package seccomp\n\n")
	g.WriteString("// syscallGroups is systemd's SystemCallFilter= groups (seccomp-util.c),\n")
	g.WriteString("// nested groups expanded, cut to the syscalls x86_64 has.\n")
	g.WriteString("var syscallGroups = map[string][]string{\n")
	for _, name := range order {
		members, err := expand(name, map[string]bool{name: true})
		if err != nil {
			return nil, "", err
		}
		list := make([]string, 0, len(members))
		for n := range members {
			list = append(list, n)
		}
		sort.Strings(list)
		fmt.Fprintf(&g, "\t// %s\n\t%q: {", sets[name].help, name)
		for i, n := range list {
			if i%6 == 0 {
				g.WriteString("\n\t\t")
			} else {
				g.WriteString(" ")
			}
			fmt.Fprintf(&g, "%q,", n)
		}
		g.WriteString("\n\t},\n")
	}
	g.WriteString("}\n")

	var tb bytes.Buffer
	tb.WriteString("// Code generated by tools/seccompgroups from golang.org/x/sys/unix; DO NOT EDIT.\n\n")
	tb.WriteString("//go:build linux && amd64\n\npackage seccomp\n\nimport \"golang.org/x/sys/unix\"\n\n")
	tb.WriteString("// syscallNumbers maps every x86_64 syscall name (lowercase, as\n")
	tb.WriteString("// systemd, strace and the man pages spell it) onto its number.\n")
	tb.WriteString("var syscallNumbers = map[string]int{\n")
	names := make([]string, 0, len(consts))
	for n := range consts {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		fmt.Fprintf(&tb, "\t%q: unix.%s,\n", n, consts[n])
	}
	tb.WriteString("}\n")

	files := map[string][]byte{}
	for file, buf := range map[string][]byte{"zgroups.go": g.Bytes(), "zsyscalls_linux_amd64.go": tb.Bytes()} {
		src, err := format.Source(buf)
		if err != nil {
			return nil, "", fmt.Errorf("%s: %w", file, err)
		}
		files[file] = src
	}
	return files, fmt.Sprintf("%d groups, %d syscalls", len(order), len(names)), nil
}
