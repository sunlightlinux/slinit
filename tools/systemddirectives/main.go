// tools/systemddirectives — regenerates the list of directives a systemd
// .service unit can hold, from a systemd checkout:
//
//	go run ./tools/systemddirectives -systemd ../systemd
//
// It reads src/core/load-fragment-gperf.gperf.in, the table systemd
// itself parses unit files with, expands its per-unit-type macros
// (EXEC_CONTEXT_CONFIG_ITEMS and the like) for Service, and writes
// pkg/config/testdata/systemd-directives.txt: one "Section Directive"
// line for every directive of [Unit], [Service] and [Install].
//
// The list is what TestEverySystemdDirectiveIsClassified checks the
// .service loader against. Without it, a directive systemd added, or one
// the loader never learned, fell through to a generic "not mapped"
// warning that nobody reads on a live load; with it, regenerating after a
// systemd release names every directive the loader has no answer for.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var (
	macroRe  = regexp.MustCompile(`(?s)\{%-?\s*macro\s+(\w+)\(type\)\s*-?%\}(.*?)\{%-?\s*endmacro\s*-?%\}`)
	macroKey = regexp.MustCompile(`(?m)^\{\{type\}\}\.(\w+),`)
	plainKey = regexp.MustCompile(`(?m)^(\w+)\.(\w+),`)
	useRe    = regexp.MustCompile(`\{\{\s*(\w+)\('(\w+)'\)\s*\}\}`)
)

// sections are the unit-file sections a .service unit can hold.
var sections = map[string]bool{"Unit": true, "Service": true, "Install": true}

// parse returns the sorted "Section Directive" lines of a gperf table.
func parse(table string) []string {
	macros := map[string][]string{}
	for _, m := range macroRe.FindAllStringSubmatch(table, -1) {
		for _, k := range macroKey.FindAllStringSubmatch(m[2], -1) {
			macros[m[1]] = append(macros[m[1]], k[1])
		}
	}
	set := map[string]bool{}
	for _, m := range plainKey.FindAllStringSubmatch(table, -1) {
		if sections[m[1]] {
			set[m[1]+" "+m[2]] = true
		}
	}
	for _, m := range useRe.FindAllStringSubmatch(table, -1) {
		if !sections[m[2]] {
			continue
		}
		for _, k := range macros[m[1]] {
			set[m[2]+" "+k] = true
		}
	}
	out := make([]string, 0, len(set))
	for k := range set {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func main() {
	sd := flag.String("systemd", "../systemd", "path to a systemd checkout")
	out := flag.String("o", "pkg/config/testdata/systemd-directives.txt", "output file")
	flag.Parse()

	table, err := os.ReadFile(filepath.Join(*sd, "src/core/load-fragment-gperf.gperf.in"))
	if err != nil {
		fmt.Fprintln(os.Stderr, "systemddirectives:", err)
		os.Exit(1)
	}
	lines := parse(string(table))
	if len(lines) < 300 {
		// The table's layout changed under the regular expressions; a
		// short list would make the check pass for directives it lost.
		fmt.Fprintf(os.Stderr, "systemddirectives: only %d directives found — has the gperf layout changed?\n", len(lines))
		os.Exit(1)
	}

	version := "unknown"
	if v, err := exec.Command("git", "-C", *sd, "describe", "--tags").Output(); err == nil {
		version = strings.TrimSpace(string(v))
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "# Generated by tools/systemddirectives from systemd %s\n", version)
	fmt.Fprintf(&b, "# (src/core/load-fragment-gperf.gperf.in). DO NOT EDIT; regenerate:\n")
	fmt.Fprintf(&b, "#   go run ./tools/systemddirectives -systemd ../systemd\n")
	for _, l := range lines {
		b.WriteString(l)
		b.WriteByte('\n')
	}
	if err := os.WriteFile(*out, b.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "systemddirectives:", err)
		os.Exit(1)
	}
	fmt.Printf("%s: %d directives from systemd %s\n", *out, len(lines), version)
}
