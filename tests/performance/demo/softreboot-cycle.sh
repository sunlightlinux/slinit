#!/bin/bash
# softreboot-cycle.sh — repeated `slinitctl shutdown softreboot now`
# against the full demo service tree, measuring the round trip and
# checking that every service comes back each time.
#
# Why this harness is shaped differently from cold-boot.sh: that one
# runs N QEMU boots and measures one boot each. This runs ONE QEMU boot
# and N soft reboots inside it, because consecutive soft reboots are
# where the interesting failure lives. The bug this was written after —
# nginx exiting 1 in the generation after a soft reboot, because nothing
# swept the old userspace before the re-exec — was sporadic, so a single
# cycle proved nothing and a loop proves something.
#
# `now` is deliberate. It is the impatient form: it stops waiting for
# graceful stops, which is what leaves processes still dying when the
# re-exec fires. A plain `softreboot` exercises a kinder path.
#
# How the loop is driven: the cycle counter lives in a file on the
# initramfs root, which survives a soft reboot by definition — same
# kernel, same mounts, that being the whole point of a soft reboot. A
# service injected at the end of the boot reads the counter, reports,
# and either asks for the next soft reboot or powers off. So each
# generation drives the next, and the host only has to read the serial
# console and count. Nothing on the host side can be swept, because
# nothing on the host side is inside the VM.
#
# Usage:
#   tests/performance/demo/softreboot-cycle.sh [CYCLES]    (default 10)
#
# Requires: qemu-system-x86_64, awk, sort, printf.

set -euo pipefail

CYCLES="${1:-10}"

SELF_DIR="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=_lib.sh
. "${SELF_DIR}/_lib.sh"

REPO_ROOT="$(cd "${SELF_DIR}/../../.." && pwd)"
DEMO_DIR="${REPO_ROOT}/demo"
SVC_DIR="${DEMO_DIR}/services"
BOOT_SVC="${SVC_DIR}/boot"
MARKER_SVC="${SVC_DIR}/sr-cycle"

if [ ! -f "${DEMO_DIR}/build.sh" ] || [ ! -f "${DEMO_DIR}/run.sh" ]; then
    echo "softreboot-cycle: expected demo/build.sh + demo/run.sh at ${DEMO_DIR}" >&2
    exit 2
fi

_boot_backup=""
cleanup() {
    [ -f "${MARKER_SVC}" ] && rm -f "${MARKER_SVC}"
    if [ -n "${_boot_backup}" ] && [ -f "${_boot_backup}" ]; then
        mv -f "${_boot_backup}" "${BOOT_SVC}"
    fi
}
trap cleanup EXIT INT TERM

# The driver service.
#
# Constraints from _lib.sh that apply here too: `command =` must stay
# on ONE physical line (the parser has no continuation), and a runtime
# shell variable has to be written `$$VAR` because a bare `$VAR` is
# expanded at parse time and would be empty.
#
# What each generation reports, on one line the host can parse:
#   SR-CYCLE n=<cycle> up=<uptime_sec> total=<services> started=<started>
# `total` and `started` are read from `slinitctl list`; a started entry
# carries a `+` in its state bracket. The check is that they stay equal
# to each other and constant across generations — a service that failed
# to come back shows up as started < total, and one that vanished from
# the set shows up as a changed total.
echo "→ injecting sr-cycle (dep: all-services, target ${CYCLES}) into ${SVC_DIR}/"
cat > "${MARKER_SVC}" <<'EOF'
# sr-cycle -- generated by tests/performance/demo/softreboot-cycle.sh.
type = scripted
depends-on: all-services
command = /bin/sh -c 'N=$$(cat /sr-cycles 2>/dev/null || echo 0); N=$$((N + 1)); echo $$N > /sr-cycles; U=$$(cut -d" " -f1 /proc/uptime); T=$$(slinitctl list 2>/dev/null | grep -c .); S=$$(slinitctl list 2>/dev/null | grep -c "+"); { echo "SR-CYCLE n=$$N up=$$U total=$$T started=$$S"; } > /dev/console; sync; if [ "$$N" -ge "__CYCLES__" ]; then echo SR-DONE > /dev/console; sync; sleep 1; slinitctl shutdown poweroff; else slinitctl shutdown softreboot now; fi'
EOF
sed -i "s/__CYCLES__/${CYCLES}/" "${MARKER_SVC}"

_boot_backup="${BOOT_SVC}.sr-cycle-bak"
cp "${BOOT_SVC}" "${_boot_backup}"
printf '\n# added by tests/performance/demo/softreboot-cycle.sh\nwaits-for: sr-cycle\n' \
    >> "${BOOT_SVC}"

echo "→ rebuilding initramfs (demo/build.sh)"
_build_log=$(mktemp)
if ! (cd "${DEMO_DIR}" && ./build.sh) >"${_build_log}" 2>&1; then
    echo "softreboot-cycle: demo/build.sh failed; last 40 lines:" >&2
    tail -40 "${_build_log}" >&2
    rm -f "${_build_log}"
    exit 3
fi
rm -f "${_build_log}"

# One boot, CYCLES soft reboots. The timeout has to cover the cold boot
# plus every cycle; a generous per-cycle allowance is better than a
# false failure on a loaded machine, because a real hang is caught by
# the missing SR-DONE rather than by the clock.
_timeout=$(( 60 + CYCLES * 30 ))
_log=$(mktemp)
echo "→ booting once, then ${CYCLES} × 'shutdown softreboot now' (timeout ${_timeout}s)"
timeout "${_timeout}s" bash -c \
    "cd '${DEMO_DIR}' && ./run.sh --no-monitor </dev/null >'${_log}' 2>&1" || true

_clean=$(sed 's/\x1b\[[0-9;]*[a-zA-Z]//g' "${_log}" | tr -d '\r')

# Not anchored: the marker shares its line with whatever the console
# had already emitted — a shell prompt and a bracketed-paste escape, in
# practice ("...localhost:/# SR-CYCLE n=1 ..."). An anchored match finds
# nothing and reads as "the loop never ran".
mapfile -t _lines < <(printf '%s\n' "${_clean}" | grep -o 'SR-CYCLE n=.*' || true)
if [ "${#_lines[@]}" -eq 0 ]; then
    _keep="/tmp/softreboot-cycle-$$.log"
    mv "${_log}" "${_keep}"
    echo "softreboot-cycle: no SR-CYCLE line at all — log saved: ${_keep}" >&2
    exit 4
fi

# Parse, and check liveness per generation before any timing. A fast
# cycle that came back missing a service is a failure, not a good score.
#
# The check is CONSTANCY, not started == total, and it reads 43 of 45
# on a healthy boot for a reason that cannot be designed away: the two
# that are not started are **this service and `boot`**. sr-cycle is
# STARTING while its own command runs, and `boot` waits-for sr-cycle,
# so it is still waiting. A service cannot observe a state in which it
# has already finished, so 45 of 45 is unreachable from inside.
#
# Verified by booting the demo with a probe that dumps `slinitctl list`:
# 45 entries, 43 carrying `+`, the two without being the probe
# (`[{ }<<`) and `boot` (`[[ ]<<`). It is NOT the demo tree's manual or
# triggered services, which is what this comment used to claim —
# `trigger-test` is loaded and STARTED, and `tty-autoconsole`
# (manual = yes) is not loaded at all, since nothing depends on it.
#
# So demanding equality would fail every cycle including the cold one.
# What matters is that each generation brings back exactly what the one
# before it had: a service that failed to restart shows up as a drop in
# `started`, one that vanished from the set as a change in `total`. The
# first generation sets the baseline, having booted cold.
_ups=() _fail=0 _total0="" _started0=""
for _l in "${_lines[@]}"; do
    _n=$(printf '%s\n' "${_l}"   | sed -n 's/.* n=\([0-9]*\) .*/\1/p')
    _up=$(printf '%s\n' "${_l}"  | sed -n 's/.* up=\([0-9.]*\) .*/\1/p')
    _tot=$(printf '%s\n' "${_l}" | sed -n 's/.* total=\([0-9]*\) .*/\1/p')
    _st=$(printf '%s\n' "${_l}"  | sed -n 's/.* started=\([0-9]*\).*/\1/p')
    if [ -z "${_total0}" ]; then
        _total0="${_tot}"; _started0="${_st}"
    fi

    _verdict="ok"
    if [ "${_st}" != "${_started0}" ]; then
        _verdict="FAIL started ${_st}, baseline ${_started0}"; _fail=$((_fail + 1))
    elif [ "${_tot}" != "${_total0}" ]; then
        _verdict="FAIL service set changed: ${_tot} vs ${_total0}"; _fail=$((_fail + 1))
    fi
    printf "  cycle %2s: up=%ss services=%s/%s %s\n" \
        "${_n}" "${_up}" "${_st}" "${_tot}" "${_verdict}"
    _ups+=("${_up}")
done

_done="no"
grep -q '^SR-DONE' <<<"${_clean}" && _done="yes"

# Round-trip per cycle = the uptime delta between consecutive
# generations. Uptime is the right clock here precisely because a soft
# reboot keeps the kernel: it does not reset, so the difference is the
# whole teardown + re-exec + boot of the next generation.
_deltas=()
for ((i = 1; i < ${#_ups[@]}; i++)); do
    _deltas+=("$(awk -v a="${_ups[i-1]}" -v b="${_ups[i]}" 'BEGIN{printf "%d", (b-a)*1000}')")
done

echo
echo "=== softreboot-cycle summary ==="
echo "cycles observed : ${#_lines[@]} of ${CYCLES}"
echo "reached SR-DONE : ${_done}"
echo "liveness failures: ${_fail}"
if [ "${#_deltas[@]}" -gt 0 ]; then
    printf "round trip      : median %s ms, p95 %s ms, max %s ms\n" \
        "$(perf_median "${_deltas[@]}")" \
        "$(perf_p95 "${_deltas[@]}")" \
        "$(printf '%s\n' "${_deltas[@]}" | sort -n | tail -1)"
    printf "BenchmarkSoftRebootCycle %3d   %s ms (p95 %s ms)\n" \
        "${#_deltas[@]}" \
        "$(perf_median "${_deltas[@]}")" "$(perf_p95 "${_deltas[@]}")"
fi

if [ "${_fail}" -gt 0 ] || [ "${_done}" != "yes" ] || [ "${#_lines[@]}" -ne "${CYCLES}" ]; then
    _keep="/tmp/softreboot-cycle-$$.log"
    mv "${_log}" "${_keep}"
    echo "softreboot-cycle: FAILED — log saved: ${_keep}" >&2
    exit 1
fi
rm -f "${_log}"
echo "softreboot-cycle: OK"
